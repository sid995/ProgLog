// Package auth evaluates log permissions using a Casbin model and policy.
package auth

import (
	"fmt"

	"github.com/casbin/casbin"
	"google.golang.org/grpc/codes"
	"google.golang.org/grpc/status"
)

// Authorizer checks subject/object/action tuples against a Casbin policy.
type Authorizer struct {
	enforcer *casbin.Enforcer
}

// New loads the Casbin model and policy files; Casbin handles loading failures.
func New(model, policy string) *Authorizer {
	enforcer := casbin.NewEnforcer(model, policy)
	return &Authorizer{
		enforcer: enforcer,
	}
}

// Authorize returns PermissionDenied unless the loaded policy allows the tuple.
func (a *Authorizer) Authorize(subject, object, action string) error {
	if !a.enforcer.Enforce(subject, object, action) {
		msg := fmt.Sprintf("%s not permitted to %s to %s", subject, action, object)
		st := status.New(codes.PermissionDenied, msg)
		return st.Err()
	}
	return nil
}
